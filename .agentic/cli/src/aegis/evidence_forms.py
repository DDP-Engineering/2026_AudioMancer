"""
@file evidence_forms.py
@brief Generated forms for manual evidence addition and supersession.
@details Removes evidence mutation flags while retaining strict validation,
         CLI-generated identities, durable journals, and atomic graph updates.
"""

# IMPORTS

from __future__ import annotations

import json
from hashlib import sha256
from pathlib import Path
import shutil
import tomllib
from typing import Any

from .models import Evidence, Graph
from .stage_forms import StageOperationError, stage_directory
from .store import (
    append_journal,
    next_evidence_id,
    save_graph,
    serialized_graph_mutation,
)

# PUBLIC API


@serialized_graph_mutation
def prepare_evidence_form(repo_root: Path, graph: Graph, action: str) -> Path:
    """
    @brief      Generate an add or supersede evidence form.
    @param[in]  repo_root Repository root.
    @param[in]  graph Active graph.
    @param[in]  action `add` or `supersede`.
    @return     Generated form path.
    @exception  StageOperationError If action is not `add` or `supersede`.
    """
    path = stage_directory(repo_root, graph) / "manual-evidence.toml"
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "schema_version = 3",
        f"run_id = {_q(graph.run_id)}",
        f"stage = {_q(graph.stage)}",
        f"action = {_q(action)}",
    ]
    if action == "add":
        lines.extend(
            [
                f"id = {_q(_next_evidence_id(graph))}",
                'kind = "note"',
                'result = "info"',
                'summary = ""',
                'failure_kind = ""',
                'command = ""',
                'path = ""',
                'check_id = ""',
                "exit_status = -1",
                'output_log = ""',
            ]
        )
    elif action == "supersede":
        lines.extend(
            [
                'target_id = ""',
                'superseded_by = ""',
                'reason = ""',
            ]
        )
    else:
        raise StageOperationError("evidence action must be add or supersede")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


@serialized_graph_mutation
def apply_evidence_form(repo_root: Path, graph: Graph) -> dict[str, Any]:
    """
    @brief      Validate and apply one generated manual evidence form.
    @param[in]  repo_root Repository root.
    @param[in,out] graph Active graph.
    @return     Applied action summary.
    @exception  StageOperationError If the current stage was not prepared.
    """
    record = graph.stage_records.get(graph.stage)
    if record is None:
        raise StageOperationError(
            "prepare the current stage before applying manual evidence"
        )
    path = stage_directory(repo_root, graph) / "manual-evidence.toml"
    data = _load(path)
    identity = {
        "schema_version": 3,
        "run_id": graph.run_id,
        "stage": graph.stage,
    }
    for key, value in identity.items():
        if data.get(key) != value:
            raise StageOperationError(
                f"{path}: {key} must be {value!r}; received {data.get(key)!r}"
            )
    action = _string(data, "action", path)
    if action == "add":
        _closed(
            data,
            (
                *identity,
                "action",
                "id",
                "kind",
                "result",
                "summary",
                "failure_kind",
                "command",
                "path",
                "check_id",
                "exit_status",
                "output_log",
            ),
            path,
        )
        evidence_id = _string(data, "id", path)
        if evidence_id != _next_evidence_id(graph):
            raise StageOperationError(
                f"{path}: evidence id is stale or was not generated by AEGIS"
            )
        kind = _string(data, "kind", path)
        if kind not in {"test-run", "diff", "scan", "gate", "decision", "note"}:
            raise StageOperationError(f"{path}: unsupported evidence kind {kind}")
        result = _string(data, "result", path)
        if result not in {"pass", "fail", "info"}:
            raise StageOperationError(f"{path}: unsupported evidence result {result}")
        summary = _string(data, "summary", path)
        if not summary:
            raise StageOperationError(f"{path}: summary must not be empty")
        exit_status = data["exit_status"]
        if type(exit_status) is not int:
            raise StageOperationError(f"{path}: exit_status must be an integer")
        evidence = Evidence(
            id=evidence_id,
            kind=kind,  # type: ignore[arg-type]
            result=result,  # type: ignore[arg-type]
            summary=summary,
            failure_kind=_optional(data, "failure_kind", path),
            command=_optional(data, "command", path),
            path=_optional(data, "path", path),
            stage=graph.stage,
            check_id=_optional(data, "check_id", path),
            exit_status=None if exit_status < 0 else exit_status,
            output_log=_optional(data, "output_log", path),
        )
        graph.evidence.append(evidence)
        summary_data = {"action": action, "evidence_id": evidence.id}
    elif action == "supersede":
        _closed(
            data,
            (*identity, "action", "target_id", "superseded_by", "reason"),
            path,
        )
        target_id = _string(data, "target_id", path)
        replacement_id = _string(data, "superseded_by", path)
        reason = _string(data, "reason", path)
        if not reason:
            raise StageOperationError(f"{path}: reason must not be empty")
        by_id = {item.id: item for item in graph.evidence}
        if target_id not in by_id or replacement_id not in by_id:
            raise StageOperationError(
                f"{path}: target_id and superseded_by must name existing evidence"
            )
        if target_id == replacement_id or by_id[target_id].status != "active":
            raise StageOperationError(f"{path}: invalid supersession relationship")
        target = by_id[target_id]
        target.status = "superseded"
        target.superseded_by = replacement_id
        target.supersede_reason = reason
        summary_data = {
            "action": action,
            "target_id": target_id,
            "superseded_by": replacement_id,
        }
    else:
        raise StageOperationError(f"{path}: action must be add or supersede")
    save_graph(repo_root, graph)
    append_journal(repo_root, graph.run_id, f"evidence.{action}", summary_data)
    _retire_form(
        path,
        record.retention,
        (
            f"manual-evidence-{action}-"
            f"{summary_data.get('evidence_id') or summary_data.get('target_id')}"
        ),
    )
    return summary_data


def show_evidence(repo_root: Path, graph: Graph) -> dict[str, Any]:
    """
    @brief      Report the generated form and durable evidence collection.
    @param[in]  repo_root Repository root.
    @param[in]  graph Active graph.
    @return     Stable evidence summary.
    """
    path = stage_directory(repo_root, graph) / "manual-evidence.toml"
    return {
        "form": path.relative_to(repo_root).as_posix() if path.is_file() else "",
        "evidence": [
            {
                "id": item.id,
                "kind": item.kind,
                "result": item.result,
                "status": item.status,
                "summary": item.summary,
            }
            for item in graph.evidence
        ],
    }


# LOCAL HELPERS


def _load(path: Path) -> dict[str, Any]:
    """@brief Load one manual evidence TOML form."""
    try:
        with path.open("rb") as stream:
            return tomllib.load(stream)
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise StageOperationError(f"{path}: cannot load evidence form: {exc}") from exc


def _closed(data: dict[str, Any], allowed: tuple[str, ...], path: Path) -> None:
    """@brief Reject unknown or missing strict-form keys."""
    unknown = sorted(set(data) - set(allowed))
    missing = sorted(set(allowed) - set(data))
    if unknown or missing:
        raise StageOperationError(
            f"{path}: "
            + (
                f"unknown key {unknown[0]}"
                if unknown
                else f"missing key {missing[0]}"
            )
        )


def _string(data: dict[str, Any], key: str, path: Path) -> str:
    """@brief Read one trimmed string field."""
    value = data.get(key)
    if not isinstance(value, str):
        raise StageOperationError(f"{path}: {key} must be a string")
    return value.strip()


def _optional(data: dict[str, Any], key: str, path: Path) -> str | None:
    """@brief Read one optional blank-as-none string field."""
    return _string(data, key, path) or None


def _next_evidence_id(graph: Graph) -> str:
    """
    @brief Return the next CLI-controlled evidence sequence ID.
    """
    return next_evidence_id(graph)


def _q(value: str) -> str:
    """@brief Quote one TOML string."""
    return json.dumps(value, ensure_ascii=False)


def _retire_form(path: Path, retention: str, revision_name: str) -> None:
    """
    @brief Apply captured retention to one imported manual-evidence form.
    """
    if retention == "versioned":
        destination = path.parent / "revisions" / revision_name
        destination.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, destination / path.name)
        (destination / "digest.json").write_text(
            json.dumps({"sha256": sha256(path.read_bytes()).hexdigest()}, indent=2)
            + "\n",
            encoding="utf-8",
        )
    elif retention == "discard":
        path.unlink()


